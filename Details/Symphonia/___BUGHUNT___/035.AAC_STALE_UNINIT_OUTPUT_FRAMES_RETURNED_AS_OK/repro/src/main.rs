//! Candidate 035: `AacDecoder::decode_inner` commits the output buffer's whole 1024-frame
//! capacity with `AudioBuffer::render_uninit(None)`, which only advances the frame counter, and
//! `decode_ga` then writes only the planes covered by an actually-decoded SCE/CPE element. A
//! `raw_data_block` that decodes no element (or only one channel of a stereo pair) is therefore
//! returned as `Ok` while still holding the *previous* packet's samples.
//!
//! Every ADTS byte below is written bit by bit, then handed to the real public
//! `AdtsReader` -> `AacDecoder` path. Exits 1 if any frame comes back as stale audio, 2 if a
//! well-formed control stream stopped decoding, 0 otherwise.

use symphonia_codec_aac::{AacDecoder, AdtsReader};
use symphonia_core::audio::{Audio, GenericAudioBufferRef};
use symphonia_core::codecs::CodecParameters;
use symphonia_core::codecs::audio::{AudioDecoder, AudioDecoderOptions};
use symphonia_core::formats::probe::ProbeableFormat;
use symphonia_core::io::MediaSourceStream;

#[derive(Default)]
struct BitWriter {
    bytes: Vec<u8>,
    cur: u8,
    nbits: u32,
}

impl BitWriter {
    fn bits(&mut self, val: u32, n: u32) {
        for i in (0..n).rev() {
            let bit = ((val >> i) & 1) as u8;
            self.cur = (self.cur << 1) | bit;
            self.nbits += 1;
            if self.nbits == 8 {
                self.bytes.push(self.cur);
                self.cur = 0;
                self.nbits = 0;
            }
        }
    }

    fn finish(mut self) -> Vec<u8> {
        if self.nbits > 0 {
            self.cur <<= 8 - self.nbits;
            self.bytes.push(self.cur);
        }
        self.bytes
    }
}

const GLOBAL_GAIN: u32 = 255;
const NOISE_PCM: u32 = 183;

/// One `individual_channel_stream` whose only scalefactor band uses perceptual noise substitution
/// (PNS), so the band's spectral coefficients are generated by the decoder's own LCG - no
/// Huffman-coded spectral data has to be crafted, yet the decoded output is non-silent.
fn write_ics_pns(bw: &mut BitWriter, global_gain: u32, noise_pcm: u32) {
    bw.bits(global_gain, 8); // global_gain
    // ics_info
    bw.bits(0, 1); // ics_reserved_bit
    bw.bits(0, 2); // window_sequence == ONLY_LONG_SEQUENCE
    bw.bits(0, 1); // window_shape
    bw.bits(1, 6); // max_sfb == 1
    bw.bits(0, 1); // predictor_data_present
    // section_data (long window: 5-bit section length increments)
    bw.bits(13, 4); // sect_cb == NOISE_HCB
    bw.bits(1, 5); // sect_len_incr == 1
    // scale_factor_data: first noise band carries a 9-bit PCM scalefactor
    bw.bits(noise_pcm, 9);
    bw.bits(0, 1); // pulse_data_present
    bw.bits(0, 1); // tns_data_present
    bw.bits(0, 1); // gain_control_data_present
}

fn raw_block_with_sces(n: u32) -> Vec<u8> {
    let mut bw = BitWriter::default();
    for i in 0..n {
        bw.bits(0, 3); // id == ID_SCE
        bw.bits(i, 4); // element_instance_tag
        write_ics_pns(&mut bw, GLOBAL_GAIN, NOISE_PCM);
    }
    bw.bits(7, 3); // id == ID_TERM
    bw.finish()
}

/// A well-formed stereo raw data block: one `channel_pair_element` (no common window, so it is
/// simply two `individual_channel_stream`s back to back).
fn raw_block_with_cpe() -> Vec<u8> {
    let mut bw = BitWriter::default();
    bw.bits(1, 3); // id == ID_CPE
    bw.bits(0, 4); // element_instance_tag
    bw.bits(0, 1); // common_window
    write_ics_pns(&mut bw, GLOBAL_GAIN, NOISE_PCM);
    write_ics_pns(&mut bw, GLOBAL_GAIN, NOISE_PCM);
    bw.bits(7, 3); // id == ID_TERM
    bw.finish()
}

fn raw_block_term_only() -> Vec<u8> {
    let mut bw = BitWriter::default();
    bw.bits(7, 3); // id == ID_TERM
    bw.finish()
}

fn adts_frame(payload: &[u8], sample_rate_index: u32, channel_config: u32) -> Vec<u8> {
    let frame_len = 7 + payload.len() as u32;
    let mut bw = BitWriter::default();
    bw.bits(0xfff, 12); // syncword
    bw.bits(0, 1); // MPEG-4
    bw.bits(0, 2); // layer
    bw.bits(1, 1); // protection_absent (no CRC)
    bw.bits(1, 2); // profile: object type index 1 => AAC-LC
    bw.bits(sample_rate_index, 4);
    bw.bits(0, 1); // private
    bw.bits(channel_config, 3);
    bw.bits(0, 4); // originality/home/copyright bits
    bw.bits(frame_len, 13);
    bw.bits(0x7ff, 11); // buffer fullness (VBR)
    bw.bits(0, 2); // number_of_raw_data_blocks_in_frame - 1
    let mut out = bw.finish();
    assert_eq!(out.len(), 7);
    out.extend_from_slice(payload);
    out
}

fn decode_all(data: Vec<u8>) -> Vec<Vec<Vec<f32>>> {
    let mss = MediaSourceStream::new(Box::new(std::io::Cursor::new(data)), Default::default());
    let mut reader = AdtsReader::try_probe_new(mss, Default::default()).expect("adts reader");

    let params = match reader.tracks()[0].codec_params.as_ref() {
        Some(CodecParameters::Audio(p)) => p.clone(),
        _ => panic!("no audio codec params"),
    };

    let mut decoder = AacDecoder::try_new(&params, &AudioDecoderOptions::default()).expect("aac");

    let mut out = Vec::new();
    let mut n = 0;

    while let Some(packet) = reader.next_packet().expect("next_packet") {
        n += 1;
        match decoder.decode(&packet) {
            Ok(GenericAudioBufferRef::F32(buf)) => {
                let planes: Vec<Vec<f32>> =
                    (0..buf.num_planes()).map(|i| buf.plane(i).unwrap().to_vec()).collect();
                println!(
                    "  packet {n}: Ok, frames={}, planes={}, peak per plane = {:?}",
                    buf.frames(),
                    planes.len(),
                    planes.iter().map(|p| peak(p)).collect::<Vec<_>>()
                );
                out.push(planes);
            }
            Ok(_) => panic!("unexpected sample format"),
            Err(e) => {
                println!("  packet {n}: Err({e})");
                out.push(Vec::new());
            }
        }
    }

    out
}

fn peak(p: &[f32]) -> f32 {
    p.iter().fold(0.0f32, |a, b| a.max(b.abs()))
}

fn main() {
    // 8000 Hz => sample rate index 11. Scalefactor band 0 is 12 coefficients wide there.
    const SRI: u32 = 11;

    let mut stale = 0;

    println!("scenario A: mono stream, good frame then a raw_data_block that is only ID_TERM");
    let mut file = Vec::new();
    file.extend_from_slice(&adts_frame(&raw_block_with_sces(1), SRI, 1));
    file.extend_from_slice(&adts_frame(&raw_block_term_only(), SRI, 1));
    file.extend_from_slice(&adts_frame(&raw_block_term_only(), SRI, 1));
    // frame_len == header_len, i.e. an ADTS frame with a zero-length payload.
    file.extend_from_slice(&adts_frame(&[], SRI, 1));
    let a = decode_all(file);
    assert_eq!(a.len(), 4);
    println!("  frame1 peak = {}", peak(&a[0][0]));
    for (i, f) in a.iter().enumerate().skip(1) {
        match f.first() {
            Some(p) => {
                let same = *p == a[0][0];
                println!("  frame{} == frame1 (bit identical): {}", i + 1, same);
                if same {
                    stale += 1;
                }
            }
            None => println!("  frame{}: rejected with an error", i + 1),
        }
    }

    println!();
    println!("scenario B: stereo stream, 2 SCEs then a lone SCE (channel 1 never decoded)");
    let mut file = Vec::new();
    file.extend_from_slice(&adts_frame(&raw_block_with_sces(2), SRI, 2));
    file.extend_from_slice(&adts_frame(&raw_block_with_sces(1), SRI, 2));
    let b = decode_all(file);
    assert_eq!(b.len(), 2);
    println!("  frame1 plane1 peak = {}", peak(&b[0][1]));
    if b[1].len() == 2 {
        println!("  frame2 plane0 == frame1 plane0: {}", b[1][0] == b[0][0]);
        println!("  frame2 plane1 == frame1 plane1: {}", b[1][1] == b[0][1]);
        if b[1][1] == b[0][1] {
            stale += 1;
        }
    }
    else {
        println!("  frame2: rejected with an error");
    }

    println!();
    println!("control: well-formed streams must keep decoding after the fix");
    let mut broken = 0;

    for (label, block, cfg) in [
        ("mono, 3x SCE frames", raw_block_with_sces(1), 1),
        ("stereo, 3x CPE frames", raw_block_with_cpe(), 2),
        ("stereo, 3x (SCE + SCE) frames", raw_block_with_sces(2), 2),
    ] {
        let mut file = Vec::new();
        for _ in 0..3 {
            file.extend_from_slice(&adts_frame(&block, SRI, cfg));
        }
        let c = decode_all(file);
        let ok = c.len() == 3 && c.iter().all(|f| f.len() == cfg as usize);
        println!("  {label}: all 3 frames decoded = {ok}");
        if !ok {
            broken += 1;
        }
    }

    println!();

    if broken > 0 {
        println!("REGRESSION: {broken} well-formed stream(s) no longer decode.");
        std::process::exit(2);
    }

    if stale > 0 {
        println!(
            "BUG: {stale} decoded frame(s) returned Ok while containing the *previous* packet's \
             samples, because AacDecoder::decode_inner commits the whole output buffer with \
             render_uninit() and nothing ever wrote those planes/frames."
        );
        std::process::exit(1);
    }

    println!("OK: no stale audio was returned as a successfully decoded frame.");
}
