#!/usr/bin/env bash
# One command, real GPU, writes GPU_RESULTS.md next to this script's parent.
#
# Builds three binaries from the same perf_test and compares them on the real display:
#   pristine  - internal/core + internal/renderers/femtovg at git HEAD (this session's changes out)
#   session   - the working tree (candidates 08, 09, 10 applied)
#   mimalloc  - the working tree with mimalloc as the global allocator, to bound how much of a
#               frame is allocator cost on real hardware (allocation counting is off there)
#
# Everything is written to GPU_RESULTS.md as it goes, so a shutdown loses nothing.
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
opt_dir="$(dirname "$here")"
harness="$(dirname "$opt_dir")"
repo="$(dirname "$harness")"
report="$opt_dir/GPU_RESULTS.md"
target="$repo/target/rdebug/perf_test"

if [ -z "${DISPLAY:-}" ] && [ -z "${WAYLAND_DISPLAY:-}" ]; then
    echo "No DISPLAY or WAYLAND_DISPLAY - this script wants your real GPU."
    echo "For a virtual display instead: cd $harness && just frames-xvfb-mode rects 3000 8"
    exit 1
fi

SCENES=(
    "rects 3000 "
    "rects 3000 --gradient"
    "list 100000 "
    "scroll 100000 "
    "scroll 100000 --flat-rows"
    "text 100000 "
)
FRAMES=${FRAMES:-20}
RUNS=${RUNS:-3}
# SCENE_FILTER=rects runs only the scenes whose mode matches, for a quick check.
if [ -n "${SCENE_FILTER:-}" ]; then
    filtered=()
    for scene in "${SCENES[@]}"; do
        case "$scene" in "$SCENE_FILTER"*) filtered+=("$scene");; esac
    done
    SCENES=("${filtered[@]}")
fi

median() { python3 -c "import sys;v=sorted(float(x) for x in sys.argv[1:]);print(f'{v[len(v)//2]:.2f}')" "$@"; }

# --- build the three binaries -------------------------------------------------
cd "$repo"
stashed=0
cleanup() {
    if [ "$stashed" = 1 ]; then
        cd "$repo" && git stash pop >/dev/null && echo "(restored the working tree)"
    fi
}
trap cleanup EXIT

echo "building session binary..."
cd "$harness" && cargo build --profile rdebug --bin perf_test -q || exit 1
cp "$target" /tmp/perf_test_session

echo "building mimalloc binary..."
cargo build --profile rdebug --bin perf_test -q --no-default-features \
    --features femtovg,software,mimalloc || exit 1
cp "$target" /tmp/perf_test_mimalloc

echo "building pristine binary (this session's changes stashed)..."
cd "$repo"
git stash push --quiet internal/core/properties.rs internal/core/graphics/brush.rs \
    internal/renderers/femtovg/itemrenderer.rs internal/core/Cargo.toml && stashed=1
cd "$harness"
sed -i 's/^dep-stats = \["dep:i-slint-core"\]/dep-stats = []/' Cargo.toml
python3 - <<'PY'
import pathlib, re
p = pathlib.Path("Cargo.toml")
s = p.read_text()
s = re.sub(r'i-slint-core = \{[^}]*\n\][^}]*\}', '# (pristine build: no dep-stats)', s)
p.write_text(s)
PY
cargo build --profile rdebug --bin perf_test -q || exit 1
cp "$target" /tmp/perf_test_pristine
git checkout Cargo.toml 2>/dev/null || python3 - <<'PY'
import pathlib
p = pathlib.Path("Cargo.toml")
s = p.read_text()
s = s.replace('dep-stats = []', 'dep-stats = ["dep:i-slint-core"]')
s = s.replace('# (pristine build: no dep-stats)', '''i-slint-core = { version = "=1.18.0", path = "../internal/core", features = [
  "dep-stats",
], optional = true }''')
p.write_text(s)
PY
cd "$repo" && git stash pop >/dev/null && stashed=0
cd "$harness" && cargo build --profile rdebug --bin perf_test -q || exit 1

# --- measure -----------------------------------------------------------------
renderer_info=$(/tmp/perf_test_session --help | grep "Renderers compiled in" || true)
gpu_info=$( (glxinfo -B 2>/dev/null | grep -E "OpenGL renderer|OpenGL version") || echo "glxinfo not installed")

# Never clobber an earlier report: a previous run's numbers are worth more than this one's.
if [ -f "$report" ]; then
    mv "$report" "${report%.md}_previous.md"
    echo "(previous report moved to ${report%.md}_previous.md)"
fi

{
    echo "# FemtoVG on real hardware: pristine vs this session's changes"
    echo
    echo "Generated by \`just gpu-report\` (\`___OPTIMIZATIONS___/tools/gpu_report.sh\`)."
    echo "Medians of $RUNS runs, $FRAMES frames each, \`rdebug\`, window 1280x860."
    echo
    echo '```'
    echo "$gpu_info"
    echo "$renderer_info"
    echo '```'
    echo
    echo "| scene | pristine | session | delta | mimalloc | allocations/frame pristine -> session |"
    echo "| --- | --- | --- | --- | --- | --- |"
} > "$report"

for scene in "${SCENES[@]}"; do
    set -- $scene
    mode=$1; count=$2; extra=${3:-}
    label="\`$mode\` $count $extra"
    echo "measuring $mode $count $extra ..."
    line=""
    for bin in /tmp/perf_test_pristine /tmp/perf_test_session /tmp/perf_test_mimalloc; do
        vals=""
        for _ in $(seq "$RUNS"); do
            v=$("$bin" --mode "$mode" --count "$count" $extra --frames "$FRAMES" 2>/dev/null |
                awk '/^later frames/{gsub("ms","",$3); print $3}')
            if [ -z "$v" ]; then
                echo "  !! $bin produced no numbers for '$mode $count $extra'." >&2
                echo "     Run it by hand to see why:" >&2
                echo "     $bin --mode $mode --count $count $extra --frames $FRAMES" >&2
            fi
            vals="$vals ${v:-0}"
        done
        a=$("$bin" --mode "$mode" --count "$count" $extra --frames "$FRAMES" 2>/dev/null |
            awk '/^later frames/{gsub("[()]","",$7); print $7}')
        line="$line $(median $vals) ${a:-n/a}"
    done
    set -- $line
    pristine=$1; pre_alloc=$2; session=$3; post_alloc=$4; mimalloc=$5
    delta=$(python3 -c "
p, s = float('$pristine'), float('$session')
print('n/a' if p == 0 else f'{100 * (s - p) / p:+.1f}%')")
    echo "| $label | ${pristine} ms | ${session} ms | $delta | ${mimalloc} ms | $pre_alloc -> $post_alloc |" >> "$report"
    tail -1 "$report"
done

{
    echo
    echo "## How to read it"
    echo
    echo "- **delta** is what candidates 08 (duplicate dependency registrations), 09 and 10"
    echo "  (gradient paths) are worth on this GPU."
    echo "- The **mimalloc** column bounds allocator-side work: it is the same code as *session*"
    echo "  with a ~3.3x faster allocator, so \`session - mimalloc\` is roughly what any further"
    echo "  allocation-removing change (arena, buffer pooling, candidate 06) can still buy."
    echo "- Allocation counts are hardware independent; the numbers here should match the ones in"
    echo "  \`FINAL_NUMBERS.md\`, which was measured under llvmpipe."
} >> "$report"

# --- section 2: what subtree pruning would be worth (candidate 12) ---------------
{
    echo
    echo "## Row variants of the non-virtualized list (candidate 12)"
    echo
    echo "All four are instantiated by their own \`for\` loop, so switching between them adds no"
    echo "per-row cost. \`bare\` is what a renderer that skipped the children of culled rows would"
    echo "approach; \`clipped\` is the only subtree pruning available today."
    echo
    echo "| row style | items per row | frame time | allocations/frame |"
    echo "| --- | --- | --- | --- |"
} >> "$report"

for style in layout flat clipped bare; do
    case $style in
        layout) items=5;; flat) items=4;; clipped) items=6;; bare) items=1;;
    esac
    echo "measuring row style $style ..."
    vals=""
    for _ in $(seq "$RUNS"); do
        v=$(/tmp/perf_test_session --mode scroll --count 100000 --row-style "$style" --frames "$FRAMES" 2>/dev/null | awk '/^later frames/{gsub("ms","",$3); print $3}')
        vals="$vals ${v:-0}"
    done
    a=$(/tmp/perf_test_session --mode scroll --count 100000 --row-style "$style" --frames "$FRAMES" 2>/dev/null | awk '/^later frames/{gsub("[()]","",$7); print $7}')
    echo "| \`$style\` | $items | $(median $vals) ms | ${a:-n/a} |" >> "$report"
    tail -1 "$report"
done

{
    echo
    echo "\`layout\` -> \`bare\` is the prize for pruning the children of culled items;"
    echo "\`clipped\` shows how much of that prize today's \`clip: true\` escape hatch spends on"
    echo "itself (an extra item per row). See \`12_subtree_pruning_prize/RESULT.md\`."
} >> "$report"

echo
echo "written: $report"
