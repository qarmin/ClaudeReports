#!/usr/bin/env bash
# Create an isolated git worktree for one bug-hunt candidate, pre-seeded with the main tree's
# already-built `build/` + `dist/` so `./y.sh build` only has to recompile what actually changed.
#
# Worktrees live INSIDE the project (tmp/wt/, gitignored) on purpose: the Bash sandbox mounts
# everything outside the primary working directory read-only, so a worktree anywhere else cannot
# be built in.
#
# Usage:  bash ___BUGHUNT___/tools/new_worktree.sh 001.some_candidate_name
# Prints the absolute worktree path on stdout (last line).
set -euo pipefail

NAME="${1:?usage: new_worktree.sh <NNN.candidate_name>}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
WT="$ROOT/tmp/wt/$NAME"

if [ -e "$WT" ]; then
    echo "worktree $WT already exists - reusing it" >&2
    echo "$WT"
    exit 0
fi

mkdir -p "$ROOT/tmp/wt"
git -C "$ROOT" worktree add --detach "$WT" HEAD >&2

# ~1.4G, ~3s on NVMe. A real copy, not hardlinks: a hardlinked target dir would let a candidate's
# rustc truncate a file the main tree still depends on. Only build/ is seeded - it holds the cargo
# caches (cranelift deps + sysroot sources) that make the difference; dist/ is regenerated by
# ./y.sh build anyway and its wrappers bake in an absolute path, so copying it would be wrong.
if [ -d "$ROOT/build" ]; then
    echo "[seed] copying prebuilt build/ (~1.4G)" >&2
    cp -a "$ROOT/build" "$WT/build"
else
    echo "[seed] main tree has no build/ yet - candidate will do a full ./y.sh build" >&2
fi

# download/ holds the external test repos `./y.sh prepare` fetched (rand, regex, portable-simd,
# ...). Without it `./y.sh test` aborts partway through with "Please run ./y.sh prepare".
if [ -d "$ROOT/download" ]; then
    echo "[seed] copying download/ so ./y.sh test can run the external test repos too" >&2
    cp -a "$ROOT/download" "$WT/download"
fi

cat >&2 <<EOF
[ready] $WT
        cd $WT && ./y.sh build          # ~25-60s thanks to the seeded build/
        bash $ROOT/___BUGHUNT___/tools/diffcheck.sh <file.rs>   # CLIF_ROOT=$WT for the patched side
EOF

echo "$WT"
