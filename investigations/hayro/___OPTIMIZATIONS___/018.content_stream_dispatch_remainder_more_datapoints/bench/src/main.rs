//! Bench for candidate 018: re-run candidate 007's `Tf`-resolution-cache fix (same
//! `patch.diff`, verbatim - identical to candidates 007 and 012) against three more PDFs to
//! add data points on how the win scales with `Tf`-call frequency and font-reuse rate:
//!
//! - `issue391.pdf` (real corpus file, `hayro-tests/pdfs/load/`): 34 `Tf` calls on its first
//!   page - a third real-world data point between `fonts_type1_latex.pdf`'s 26 and `img.pdf`'s
//!   326.
//! - `image_cmyk_icc_jpg.pdf` (real corpus file, `hayro-tests/pdfs/custom/`): an image-only
//!   page with 0 `Tf` calls - included as a "does the fix cost anything when never exercised"
//!   check, not a scaling data point.
//! - `cache_defeating.pdf` (synthetic, generated by `../testdata/gen_cache_defeating_pdf.py`):
//!   326 `Tf` calls (matching `img.pdf`'s count) but cycling through 8 distinct standard-14
//!   fonts round-robin, so no two consecutive `Tf` calls ever reference the same font - the
//!   worst case for a resource-name-keyed cache, which never hits.
//!
//! Renders the selected PDF's first page N times, discards the first 10% as warmup, reports
//! min/p50/mean/p95/max of the render() time, and hashes every produced pixmap (FNV-1a over the
//! premultiplied RGBA8 bytes) - every iteration and both variants (baseline/patched) must
//! produce the same hash for the run to be reported as bit-exact.
//!
//! Run with: `cargo run --release -- <pdf-name> [iterations]`, where `<pdf-name>` is one of
//! `issue391`, `image_cmyk_icc_jpg`, `cache_defeating`.

use hayro::hayro_interpret::InterpreterSettings;
use hayro::hayro_syntax::Pdf;
use hayro::{RenderCache, RenderSettings, render};
use std::time::{Duration, Instant};

const ISSUE391_PDF: &[u8] = include_bytes!("../../testdata/issue391.pdf");
const IMAGE_CMYK_ICC_JPG_PDF: &[u8] = include_bytes!("../../testdata/image_cmyk_icc_jpg.pdf");
const CACHE_DEFEATING_PDF: &[u8] = include_bytes!("../../testdata/cache_defeating.pdf");

fn fnv1a(data: &[u8]) -> u64 {
    let mut hash: u64 = 0xcbf29ce484222325;
    for &b in data {
        hash ^= b as u64;
        hash = hash.wrapping_mul(0x100000001b3);
    }
    hash
}

fn main() {
    let pdf_name = std::env::args().nth(1).unwrap_or_else(|| "issue391".to_string());
    let iterations: usize = std::env::args()
        .nth(2)
        .and_then(|s| s.parse().ok())
        .unwrap_or(300);

    let pdf_bytes = match pdf_name.as_str() {
        "issue391" => ISSUE391_PDF,
        "image_cmyk_icc_jpg" => IMAGE_CMYK_ICC_JPG_PDF,
        "cache_defeating" => CACHE_DEFEATING_PDF,
        other => panic!("unknown pdf name: {other}"),
    };

    let pdf = Pdf::new(pdf_bytes.to_vec()).unwrap();
    let cache = RenderCache::new();
    let settings = InterpreterSettings::default();
    let page = pdf.pages().iter().next().unwrap();

    let mut durations = Vec::with_capacity(iterations);
    let mut hashes = Vec::with_capacity(iterations);

    for _ in 0..iterations {
        let t = Instant::now();
        let pixmap = render(
            &page,
            &cache,
            &settings,
            &RenderSettings {
                x_scale: 1.0,
                y_scale: 1.0,
                ..Default::default()
            },
        );
        let elapsed = t.elapsed();
        let bytes: Vec<u8> = pixmap
            .data()
            .iter()
            .flat_map(|px| px.to_u8_array())
            .collect();
        let hash = fnv1a(&bytes);
        std::hint::black_box(&pixmap);
        durations.push(elapsed);
        hashes.push(hash);
    }

    let warmup = (iterations / 10).max(1);
    let mut timed: Vec<Duration> = durations[warmup..].to_vec();
    timed.sort();

    let n = timed.len();
    let min = timed[0];
    let p50 = timed[n / 2];
    let p95 = timed[(n * 95 / 100).min(n - 1)];
    let max = timed[n - 1];
    let mean: Duration = timed.iter().sum::<Duration>() / n as u32;

    let first_hash = hashes[0];
    let all_same = hashes.iter().all(|h| *h == first_hash);

    println!("pdf={pdf_name} iterations={iterations} (warmup={warmup} discarded)");
    println!(
        "render() time: min={:.4}ms p50={:.4}ms mean={:.4}ms p95={:.4}ms max={:.4}ms",
        min.as_secs_f64() * 1e3,
        p50.as_secs_f64() * 1e3,
        mean.as_secs_f64() * 1e3,
        p95.as_secs_f64() * 1e3,
        max.as_secs_f64() * 1e3,
    );
    println!("pixmap hash (FNV-1a of RGBA8 bytes): {first_hash:#018x}");
    println!("all iterations produced identical pixmap hash: {all_same}");
}
