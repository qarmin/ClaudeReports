#!/usr/bin/env python3
"""Generate a single-file exhaustive differential test for simd_funnel_shl / simd_funnel_shr.

The generated program is meant to be fed to ___BUGHUNT___/tools/diffcheck.sh, i.e. built once
with plain rustc (LLVM = the oracle) and once with dist/rustc-clif, with both run-time outputs
diffed. It additionally carries its own scalar reference implementation of the funnel shift, so a
case where *both* backends are wrong still shows up (as `SELFCHECK` lines) instead of silently
comparing equal.

Coverage per (lane type, lane count):
  * every shift amount 0..bits-1, on every lane, via a rotating shift vector
  * boundary operand values (0, 1, MAX, MIN/sign bit, 0x55.., 0xAA..) plus an xorshift stream
Lane counts go past 128 bits on purpose: Cranelift has no >128-bit vector type, so the wide cases
exercise the scalarized path.

    python3 gen_funnel_sweep.py > /tmp/funnel_sweep.rs
    bash ___BUGHUNT___/tools/diffcheck.sh /tmp/funnel_sweep.rs
"""

TYPES = [
    ("u8", "u8", 8),
    ("i8", "u8", 8),
    ("u16", "u16", 16),
    ("i16", "u16", 16),
    ("u32", "u32", 32),
    ("i32", "u32", 32),
    ("u64", "u64", 64),
    ("i64", "u64", 64),
    ("u128", "u128", 128),
    ("i128", "u128", 128),
]

# vector total bit widths to build for each lane type
LANE_COUNTS = [2, 4, 8, 16, 32, 64]

HEADER = r'''// GENERATED by ___BUGHUNT___/tools/gen_funnel_sweep.py - do not edit by hand.
#![feature(core_intrinsics, repr_simd)]
#![allow(internal_features, non_camel_case_types)]

use std::intrinsics::simd::{simd_funnel_shl, simd_funnel_shr};
use std::mem::transmute;

static mut SELFCHECK_FAILURES: u32 = 0;

struct Rng(u64);
impl Rng {
    fn next(&mut self) -> u64 {
        // xorshift64*, so the operand stream is identical on both backends
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
}

macro_rules! reference {
    ($uty:ty, $bits:expr) => {
        // (a:b) as a 2*bits value, shifted, keeping the high half (shl) or low half (shr)
        fn ref_shl(a: $uty, b: $uty, s: u32) -> $uty {
            let s = s % $bits;
            let lo = if s == 0 { 0 } else { b >> ($bits - s) };
            (a << s) | lo
        }
        fn ref_shr(a: $uty, b: $uty, s: u32) -> $uty {
            let s = s % $bits;
            let hi = if s == 0 { 0 } else { a << ($bits - s) };
            hi | (b >> s)
        }
    };
}
'''


def gen_case(name, lane_ty, uty, bits, count):
    total = bits * count
    return f'''
mod case_{name} {{
    use super::*;
    #[repr(simd)]
    #[derive(Copy, Clone)]
    pub struct V([{lane_ty}; {count}]);
    reference!({uty}, {bits});

    fn boundary(i: usize) -> {uty} {{
        match i % 8 {{
            0 => 0,
            1 => 1,
            2 => {uty}::MAX,
            3 => 1 << ({bits} - 1),
            4 => {uty}::MAX >> 1,
            5 => !({uty}::MAX >> 1) | 1,
            6 => 0x5555_5555_5555_5555u64 as {uty},
            _ => 0xAAAA_AAAA_AAAA_AAAAu64 as {uty},
        }}
    }}

    pub fn run() {{
        let mut rng = Rng(0x1234_5678_9abc_def0 ^ {total});
        let mut a = [0{uty}; {count}];
        let mut b = [0{uty}; {count}];
        let mut s = [0{uty}; {count}];
        // `rounds` covers every shift amount on every lane, then keeps going with random operands
        for round in 0..({bits} + 48) {{
            for lane in 0..{count} {{
                if round < {bits} {{
                    a[lane] = boundary(round + lane);
                    b[lane] = boundary(round + lane + 3);
                }} else {{
                    a[lane] = rng.next() as {uty} ^ ((rng.next() as {uty}) << ({bits} / 2));
                    b[lane] = rng.next() as {uty} ^ ((rng.next() as {uty}) << ({bits} / 2));
                }}
                s[lane] = ((round + lane) % {bits}) as {uty};
            }}
            let (va, vb, vs): (V, V, V) =
                unsafe {{ (transmute(a), transmute(b), transmute(s)) }};
            let got_shl: [{uty}; {count}] = unsafe {{ transmute(simd_funnel_shl(va, vb, vs)) }};
            let got_shr: [{uty}; {count}] = unsafe {{ transmute(simd_funnel_shr(va, vb, vs)) }};
            for lane in 0..{count} {{
                let sh = s[lane] as u32;
                let want_shl = ref_shl(a[lane], b[lane], sh);
                let want_shr = ref_shr(a[lane], b[lane], sh);
                println!("{name} r{{round}} l{{lane}} shl {{:x}} shr {{:x}}", got_shl[lane], got_shr[lane]);
                if got_shl[lane] != want_shl {{
                    println!(
                        "SELFCHECK shl {name} round={{round}} lane={{lane}} a={{:x}} b={{:x}} s={{sh}} got={{:x}} want={{:x}}",
                        a[lane], b[lane], got_shl[lane], want_shl
                    );
                    unsafe {{ SELFCHECK_FAILURES += 1 }};
                }}
                if got_shr[lane] != want_shr {{
                    println!(
                        "SELFCHECK shr {name} round={{round}} lane={{lane}} a={{:x}} b={{:x}} s={{sh}} got={{:x}} want={{:x}}",
                        a[lane], b[lane], got_shr[lane], want_shr
                    );
                    unsafe {{ SELFCHECK_FAILURES += 1 }};
                }}
            }}
        }}
    }}
}}
'''


def main():
    out = [HEADER]
    names = []
    for lane_ty, uty, bits in TYPES:
        for count in LANE_COUNTS:
            if bits * count > 1024:
                continue
            name = f"{lane_ty}x{count}"
            names.append(name)
            out.append(gen_case(name, lane_ty, uty, bits, count))
    out.append("\nfn main() {\n")
    for n in names:
        out.append(f"    case_{n}::run();\n")
    out.append(
        '    let f = unsafe { SELFCHECK_FAILURES };\n'
        '    println!("selfcheck failures: {f}");\n'
        "}\n"
    )
    print("".join(out))


if __name__ == "__main__":
    main()
